#!/usr/bin/env python3
"""Generate ``docs/original-language/reference/functions.md`` from ``functions.json``.

``functions.json`` is the machine-readable inventory of everything the mod
accepts inside a ``$${ ... }$$`` block. It is the only complete source we have,
so the reference page is generated from it instead of being maintained by hand:
that way the documentation can never drift from the data the transpiler uses.

Usage
-----
    python3 tools/gen_function_docs.py            # write the page
    python3 tools/gen_function_docs.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FUNCTIONS_JSON = REPO_ROOT / "functions.json"
TARGET = REPO_ROOT / "docs" / "original-language" / "reference" / "functions.md"

# Display order of the categories, with a short human description for each.
CATEGORIES: list[tuple[str, str]] = [
    ("Control Flow", "Blocks that decide what runs: conditionals, loops, waits."),
    ("Variables", "Read and change variables, arrays and flags."),
    ("Calculations", "Maths, string handling, regex, item and block queries."),
    ("Input", "Fake key presses, mouse work and chat output."),
    ("GUI", "Inventory screens, slots, titles and toasts."),
    ("Settings", "Client settings: view, chat, sound, key binds."),
    ("Mod related", "Macros calling macros, configs, labels and GUI screens."),
    ("World", "Actions that touch the world or the connection."),
]


def clean_name(name: str) -> str:
    """``CLEARCHAT()`` in the JSON should be ``CLEARCHAT``."""
    return name.strip().rstrip("()").strip()


def clean_description(text: str) -> str:
    text = (text or "").strip()
    # A few descriptions kept the opening quote of the original JSON string.
    # Otherwise the text is reproduced verbatim: this page reports the inventory,
    # it does not editorialise about it.
    text = text.lstrip('"').rstrip()
    text = " ".join(text.split())
    return text or "—"


def clean_definition(definition: str, name: str) -> str:
    definition = (definition or "").strip()
    if not definition:
        return name
    # Normalise "NAME()" style definitions so they read like the others.
    if definition.endswith("()"):
        return definition[:-2]
    return definition


def signature_parts(definition: str) -> tuple[str, list[str]]:
    """Split ``NAME(<a>,[b],c)`` into the name and its parameter strings."""
    if "(" not in definition:
        return definition, []
    head, _, tail = definition.partition("(")
    params = tail.rstrip(")")
    if not params.strip():
        return head.strip(), []
    return head.strip(), [p.strip() for p in params.split(",")]


def render(entries: dict) -> str:
    grouped: dict[str, list[tuple[str, dict]]] = {c: [] for c, _ in CATEGORIES}
    for name, data in entries.items():
        category = data.get("category", "Other")
        grouped.setdefault(category, []).append((clean_name(data.get("name", name)), data))

    total = sum(len(items) for items in grouped.values())
    lines: list[str] = [
        "<!-- Generated by tools/gen_function_docs.py — do not edit by hand. -->",
        "",
        "# Function reference",
        "",
        f"All **{total}** keywords known to the mod, grouped by the category used in",
        "`functions.json`. Signatures follow the original convention:",
        "",
        "* `<name>` — required argument;",
        "* `[name]` — optional argument;",
        "* `<&name>` — argument is a variable that receives a **string**;",
        "* `<#name>` — argument is a variable that receives a **number**;",
        "* `<name[]>` — argument is an array.",
        "",
        "Keyword names are matched case-insensitively by the transpiler and are",
        "written in upper case here for readability.",
        "",
        "---",
        "",
    ]

    for category, blurb in CATEGORIES + [
        (c, "Keywords not yet categorised.") for c in grouped if c not in dict(CATEGORIES)
    ]:
        items = grouped.get(category, [])
        if not items:
            continue
        lines += [f"## {category}", "", blurb, "", "| Keyword | Signature | Description |", "| --- | --- | --- |"]
        for name, data in sorted(items, key=lambda item: item[0]):
            definition = clean_definition(data.get("definition", ""), name)
            description = clean_description(data.get("description", ""))
            lines.append(f"| `{name}` | `{definition}` | {description} |")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only verify that the page is up to date")
    args = parser.parse_args(argv)

    entries = json.loads(FUNCTIONS_JSON.read_text(encoding="utf-8"))
    content = render(entries)

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"{TARGET.relative_to(REPO_ROOT)} is out of date; run tools/gen_function_docs.py")
            return 1
        print(f"{TARGET.relative_to(REPO_ROOT)} is up to date")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
